/** Escurece a cor para o fundo da arte. */
const shade = (hex: string, f: number) => "#" + [1, 3, 5].map((i) => Math.round(parseInt(hex.slice(i, i + 2), 16) * f).toString(16).padStart(2, "0")).join("");

/** Letra(s) grandes do tile: o texto da arte se for curto, senão a inicial. */
const letterOf = (name: string, glyph: string) => (glyph.length <= 2 ? glyph : name.replace(/^The /, "")[0]).toUpperCase();

const ORIGINAL_C2: Record<string, string> = { roblox: "#2A1F4D", valorant: "#4A1620", lol: "#3A3018", freefire: "#4D2A10", minecraft: "#1E3D1A", steam: "#163246", fortnite: "#33184F", cs2: "#3D3016", genshin: "#163C42" };
const ORIGINAL_LETTER: Record<string, string> = { roblox: "R", valorant: "V", lol: "L", freefire: "FF", minecraft: "M", steam: "S", fortnite: "F", cs2: "CS", genshin: "G" };

export const GAME_CATALOG: CatalogGame[] = RAW.map(([slug, name, glyph, c1], sort) => ({
  slug,
  name,
  glyph,
  c1,
  c2: ORIGINAL_C2[slug] ?? shade(c1, 0.27),
  letter: ORIGINAL_LETTER[slug] ?? letterOf(name, glyph),
  sort: slug === "outros" ? 9999 : sort,
}));

